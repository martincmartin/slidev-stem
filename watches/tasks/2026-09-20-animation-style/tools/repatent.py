#!/usr/bin/env python3
"""Derive set 5, "Patent, weighted", from set 4, "Patent".

    .venv/bin/python3 tasks/2026-09-20-animation-style/tools/repatent.py

Writes deck/public/timekeepers/patent-weighted/. EDIT THIS FILE, not those SVGs.

WHAT THE SET IS FOR. Both patent sets are after the CLARITY of a technical
drawing -- the line-weight hierarchy that separates outline from interior from
detail, the 45 degree section hatch, the stipple standing in for tone. That is a
way of making a small drawing legible, and it happens to be the way patent plates
and engineering elevations make theirs legible. The goal is NOT to be recognisable
AS a patent drawing.

    REFERENCE NUMERALS, LEADER LINES AND DOT TERMINATORS ARE DELIBERATELY ABSENT.
    An earlier version of this set drew them; removing them was an explicit choice
    by the user (2026-09-21). DO NOT ADD THEM BACK without the user's explicit
    direction -- not as a "restoration", not as an affordance for the speaker, not
    because a comment elsewhere describes the USPTO numbering convention.

So this set is set 4 with its measured deficits repaired and nothing else changed.
The name says what the repair was: the weights.

Unlike set 1, set 4's PALETTE is already optimal -- one ink #2A2520 on paper
#FAF7F0, 13.10:1, the same ink Bold and Linocut win with. Nothing here touches
colour. Two things were wrong.

 1. NO LINE IN THE SET REACHES THE VENUE'S RESOLUTION LIMIT. The heaviest is 2.5
    units = 1.27 CSS px against the 1.64 px an eye resolves at 55in @ 7 m; the
    lightest is 0.96 = 0.49. The whole hierarchy sits under the floor.
 2. THE TEXTURES DISSOLVE TO NOTHING RATHER THAN TO GREY. The 45 degree section
    hatch is a 1-unit line on a 6-unit pitch: 0.51 px of ink every 3.05 px. T3's
    rule is that anything under ~2 CSS px reads as flat tint -- but that assumes
    ink is there to tint with. At 17% coverage of a 0.51 px line there is not.
    Engraved survives distance because its hatching "disappears into grey, not
    into nothing" (§5). Set 4's disappears into nothing.

WHY COMPRESS THE WEIGHTS RATHER THAN SCALE THEM. Uniform x3 measures best of
anything tried (Fmax 0.240) and is visibly wrong: it lands the top line at 3.81 px,
heavier than Bold's modal stroke, and the drawing stops reading as fine technical
line work at all -- while STILL leaving the thinnest line at 1.46 px, under the
floor. Scaling preserves a ratio that was never the point. What matters is that the
bottom of the hierarchy clears the floor and the top stays light, so the span is
remapped instead: [0.96, 2.5] -> [3.4, 7.0] units = [1.73, 3.56] CSS px. Everything
is resolvable, the top is lighter than Bold, and 2.60x of hierarchy becomes 2.06x.

    strategy                    thin/thick px   hold   p90    Fmax   (55in @ 7 m)
    set 4, as drawn               0.49 / 1.27   2.14   2.98   0.000
    uniform x2                    0.98 / 2.54   3.59   7.72   0.073
    uniform x3 (too heavy)        1.46 / 3.81   6.54  12.33   0.240
    compressed to 3.4-6.0u        1.73 / 3.05   4.78  10.29   0.164
    THIS SET (3.4-7.0u + texture) 1.73 / 3.56   6.03  11.90   0.223

THE NUMERALS WERE COSTING MEASUREMENT, NOT EARNING IT. The version that drew them
measured 19.0% -> 20.2% ink and 6.03 / 11.90 / 0.223 -> 5.62 / 11.85 / 0.208. They
LOWERED every score, because a leader line was 3.4u = 1.73 CSS px (the thinnest
weight in the set, right on the 1.64 px floor) and a 16u digit has ~0.9 px stems,
well under it. A fifth of a mark's worth of ink was being spent below the venue's
resolution limit, dragging the median down. So the aesthetic call and the
arithmetic agree here, which is not usually how this goes: removing them is worth
+7% on hold and +7% on flare headroom. See README §8.8.
"""
import re, pathlib

ROOT = pathlib.Path(__file__).resolve().parents[3]
# The art these tools read. Until 2026-09-21 this was the project root's
# public/timekeepers/, which held all sixteen sets because the live deck showed all
# sixteen. The live deck now ships one set, so the sets live in this archive's own
# deck/ and the tools read them from there -- which is also what makes the archive
# runnable after the live deck has moved on. See README S14.
ART = pathlib.Path(__file__).resolve().parents[1] / "deck/public/timekeepers"

SRC = ART / "patent"
OUT = ART / "patent-weighted"
SUBJECTS = ["sundial", "water-clock", "candle", "hourglass"]

LO_U, HI_U = 0.96, 2.5          # set 4's actual span, asserted below
LO_OUT, HI_OUT = 3.4, 7.0       # 1.73 .. 3.56 CSS px on a 122 px card
HATCH_W, STIPPLE_R = 2.2, 1.7   # section hatch line, stipple dot radius

STAMP = ("<!-- GENERATED by tasks/2026-09-20-animation-style/tools/repatent.py from\n"
         "     deck/public/timekeepers/patent/. Edit that tool, not this file. -->")


def remap(w):
    return LO_OUT + (w - LO_U) * (HI_OUT - LO_OUT) / (HI_U - LO_U)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for s in SUBJECTS:
        raw = (SRC / f"{s}.svg").read_text()
        assert "<text" not in raw, f"{s}.svg already carries text; rewrite this tool"
        colours = {c.upper() for c in re.findall(r"#[0-9A-Fa-f]{6}", raw)}
        assert colours <= {"#2A2520", "#FAF7F0"}, f"{s}.svg has unexpected colours {colours}"

        # The section-hatch and stipple primitives live INSIDE <pattern>, where a
        # stroke-width is a texture parameter and not a line weight. Set them first,
        # then hide them from the remap behind a marker.
        hatch_re = r'(<line x1="0" y1="0" x2="0" y2="6" stroke="#2A2520" stroke-width=")[0-9.]+(")'
        stip_re = r'(<circle cx="[0-9.]+" cy="[0-9.]+" r=")1\.1(")'
        has_hatch, has_stip = re.search(hatch_re, raw), re.search(stip_re, raw)
        raw = re.sub(hatch_re, rf'\g<1>{HATCH_W}\g<2>', raw)
        raw = re.sub(stip_re, rf'\g<1>{STIPPLE_R}\g<2>', raw)
        raw = re.sub(r'(<line x1="0" y1="0" x2="0" y2="6" stroke="#2A2520" )stroke-width="([0-9.]+)"',
                     r'\g<1>__PW__="\g<2>"', raw)

        widths = [float(w) for w in re.findall(r'stroke-width="([0-9.]+)"', raw)]
        assert widths, f"{s}.svg has no stroke-width"
        assert min(widths) >= LO_U and max(widths) <= HI_U, \
            f"{s}.svg weights {min(widths)}..{max(widths)} fall outside the assumed {LO_U}..{HI_U}"
        raw = re.sub(r'stroke-width="([0-9.]+)"',
                     lambda m: f'stroke-width="{remap(float(m.group(1))):.2f}"', raw)
        raw = raw.replace("__PW__", "stroke-width")

        lines = raw.split("\n")
        assert lines[0].startswith("<svg "), f"{s}.svg does not open with <svg"
        raw = "\n".join([lines[0], STAMP] + lines[1:])

        assert raw.rstrip().endswith("</svg>")
        # Guard the 2026-09-21 decision: the markup (comments excluded, since they
        # explain the decision) carries no numerals and so no <text> at all.
        assert "<text" not in re.sub(r"<!--.*?-->", "", raw, flags=re.S), \
            f"{s}.svg gained numerals; they were removed on purpose (see the docstring)"
        (OUT / f"{s}.svg").write_text(raw.rstrip() + "\n")
        print(f"  {s:<12} hatch={'yes' if has_hatch else '-':<4} stipple={'yes' if has_stip else '-':<4}")

    n = sum((OUT / f"{s}.svg").stat().st_size for s in SUBJECTS)
    o = sum((SRC / f"{s}.svg").stat().st_size for s in SUBJECTS)
    k = 122 / 240
    print(f"patent-weighted: {n/1024:.1f} KB  (set 4 is {o/1024:.1f} KB)")
    print(f"   weights [{LO_U}, {HI_U}] -> [{LO_OUT}, {HI_OUT}] units "
          f"= [{LO_OUT*k:.2f}, {HI_OUT*k:.2f}] CSS px; hierarchy "
          f"{HI_U/LO_U:.2f}x -> {HI_OUT/LO_OUT:.2f}x")
    print(f"   hatch line 1 -> {HATCH_W}u, stipple r 1.1 -> {STIPPLE_R}u, no numerals")


if __name__ == "__main__":
    main()
